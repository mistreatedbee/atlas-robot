"""Core data types. All timestamps are integer milliseconds since the Unix epoch, UTC."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum

TIMEFRAME_MS: dict[str, int] = {
    "M1": 60_000,
    "M5": 300_000,
    "M15": 900_000,
    "M30": 1_800_000,
    "H1": 3_600_000,
    "H4": 14_400_000,
    "D1": 86_400_000,
}


def timeframe_ms(timeframe: str) -> int:
    try:
        return TIMEFRAME_MS[timeframe]
    except KeyError:
        raise ValueError(f"unknown timeframe {timeframe!r}; expected one of {sorted(TIMEFRAME_MS)}") from None


class VolumeKind(StrEnum):
    """What the `volume` field of a candle actually measures. Never mix these in one analysis."""

    BASE_ASSET_TRADED = "base_asset_traded"  # exchange-reported traded quantity, in base asset units
    TICK_COUNT = "tick_count"  # number of quote updates; a broker-specific activity PROXY, not traded volume
    SYNTHETIC = "synthetic"  # generated sample data; meaningless for research
    NONE = "none"  # source provides no volume


class PriceBasis(StrEnum):
    """Which price stream the primary OHLC columns represent."""

    TRADE = "trade"  # last-traded prices (exchanges)
    BID = "bid"
    ASK = "ask"
    MID = "mid"


class DataLabel(StrEnum):
    """Provenance class. Synthetic sample data must never be presented as market data."""

    LIVE_SOURCE = "live_source"  # fetched from a real provider API
    USER_FILE = "user_file"  # imported from a file the user supplied (e.g. a broker export)
    SYNTHETIC_SAMPLE = "synthetic_sample"  # generated by scripts/generate_sample_data.py


class ValidationStatus(StrEnum):
    VALID = "valid"
    WARNING = "warning"
    INVALID = "invalid"


@dataclass(frozen=True, slots=True)
class Candle:
    """One completed OHLC bar.

    `open_time` is inclusive and `close_time` exclusive: close_time == open_time + timeframe.
    Optional bid/ask columns are filled only when the source actually supplies them.
    """

    instrument_id: str
    provider: str
    venue: str
    timeframe: str
    source_symbol: str
    open_time: int
    close_time: int
    open: float
    high: float
    low: float
    close: float
    price_basis: PriceBasis
    volume: float | None
    volume_kind: VolumeKind
    quote_volume: float | None = None
    trade_count: int | None = None
    bid_open: float | None = None
    bid_high: float | None = None
    bid_low: float | None = None
    bid_close: float | None = None
    ask_open: float | None = None
    ask_high: float | None = None
    ask_low: float | None = None
    ask_close: float | None = None

    def values_key(self) -> tuple:
        """The observable values, used to tell a true duplicate from a conflicting revision."""
        return (
            self.close_time, self.open, self.high, self.low, self.close, self.price_basis.value,
            self.volume, self.volume_kind.value, self.quote_volume, self.trade_count,
            self.bid_open, self.bid_high, self.bid_low, self.bid_close,
            self.ask_open, self.ask_high, self.ask_low, self.ask_close,
        )


@dataclass(frozen=True, slots=True)
class RejectedRecord:
    """A source record that could not be parsed into a Candle. Kept verbatim for audit."""

    reason: str
    raw: str


@dataclass(slots=True)
class FetchResult:
    candles: list[Candle] = field(default_factory=list)
    rejects: list[RejectedRecord] = field(default_factory=list)
